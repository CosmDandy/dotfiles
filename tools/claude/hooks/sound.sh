#!/bin/sh
# Звуковая метка события Claude Code: один тембр = одно состояние, чтобы
# различать их не глядя на экран.
#   Blow  — нужен ответ или разрешение (Notification).
#   Basso — упало (PostToolUseFailure, StopFailure).
#
# Только macOS, и только через afplay: он играет сам и не зависит ни от
# bell-action, ни от того, какое окно активно.
#
# NOTE: BEL-ветка для контейнеров удалена 2026-08-12. Хуки Claude Code
# запускаются без управляющего терминала — /dev/tty не открывается ни разу,
# ни синхронно, ни асинхронно. Значит из контейнера звука нет и быть не может;
# ветка молчала всегда, создавая впечатление, будто звук зависит от фокуса.
set -u

snd="${1:-Glass}"
f="/System/Library/Sounds/${snd}.aiff"

if command -v afplay >/dev/null 2>&1 && [ -r "$f" ]; then
    afplay "$f" 2>/dev/null &
fi

exit 0
