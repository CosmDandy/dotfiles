#!/bin/sh
# Полоса прогресса Ghostty (OSC 9;4) как индикатор состояния Claude Code.
#   maybe-start — на PostToolUse/Bash: если команда фоновая, то же, что start
#   start       — появилась фоновая задача: пульсирующая полоса (состояние 3)
#   done        — задача закрылась: если незакрытых больше нет, полосу убираем
#   error       — что-то упало: красная полоса, гаснет сама через ~14 секунд
#   reset       — снять всё (вешается на Stop: турн кончился)
#
# Почему старт ловится на PostToolUse, а снятие на Stop: событий про фоновые
# задачи нет. TaskCreated/TaskCompleted проверены логгером — на фоновые команды
# они не приходят вообще (относятся к трекеру задач), а метаданных со статусом
# у задач на диске нет, только .output. Поэтому полоса означает «в этом турне
# запускалась фоновая работа» и гаснет на конце турна. Задача, живущая дольше
# турна, потеряет полосу раньше времени — цена простоты.
#
# Почему не уведомления: у Ghostty на macOS они не работают (известный баг,
# ghostty-org/ghostty#10151) — ни OSC 9, ни OSC 777, ни даже собственное
# уведомление о копировании. Полоса же работает надёжно, в том числе когда
# Claude сидит в dev-контейнере: байты едут тем же каналом, что и текст.
#
# Учёт задач — файлами в каталоге, а не счётчиком в файле: несколько хуков
# запускаются параллельно, а mktemp и rm атомарны, инкремент числа в файле — нет.
# Нам нужно только КОЛИЧЕСТВО незакрытых задач, поэтому какой файл удалить на
# done — безразлично.
set -u

dir="${TMPDIR:-/tmp}/claude-progress"
holder="$dir/.holder"
mkdir -p "$dir" 2>/dev/null || exit 0

# Полоса живёт в терминале, а не в stdout: у хуков он перехвачен.
# Открываем tty попыткой — проверка правами врёт (в фоновых сессиях /dev/tty
# выглядит доступным, но не открывается).
# CLAUDE_PROGRESS_TTY — только для проверки: позволяет направить полосу в
# конкретный терминал оттуда, где своего tty нет (фоновая сессия, тест).
open_tty() { { exec 3>"${CLAUDE_PROGRESS_TTY:-/dev/tty}"; } 2>/dev/null; }
state() { printf '\033]9;4;%s;%s\007' "$1" "${2:-0}" >&3 2>/dev/null; }

# Сколько задач висит (файлы задач — всё, кроме каталога-локи держателя)
pending() { find "$dir" -type f -name 'task.*' 2>/dev/null | wc -l | tr -d ' '; }

case "${1:-}" in
maybe-start)
    # Вешается на PostToolUse/Bash, то есть срабатывает на КАЖДУЮ команду.
    # Пускаем дальше только фоновые: grep по payload дешевле, чем звать jq.
    grep -q '"run_in_background"[[:space:]]*:[[:space:]]*true' 2>/dev/null || exit 0
    set -- start
    ;;
esac

case "${1:-}" in
start)
    open_tty || exit 0
    mktemp "$dir/task.XXXXXX" >/dev/null 2>&1 || exit 0
    state 3
    # Держатель подновляет полосу, пока задачи есть: без обновления Ghostty
    # гасит её через ~14 секунд. mkdir атомарен — держатель гарантированно один.
    if mkdir "$holder" 2>/dev/null; then
        (
            while [ "$(pending)" -gt 0 ]; do
                state 3
                sleep 8
            done
            state 0
            rmdir "$holder" 2>/dev/null
        ) >/dev/null 2>&1 &
    fi
    ;;
done)
    open_tty || exit 0
    # снимаем ОДИН любой файл задачи — важно число, а не соответствие
    f=$(find "$dir" -type f -name 'task.*' 2>/dev/null | head -1)
    [ -n "$f" ] && rm -f "$f" 2>/dev/null
    # если держателя нет (например, полоса ставилась не нами) — убираем сами
    [ "$(pending)" -eq 0 ] && [ ! -d "$holder" ] && state 0
    ;;
error)
    open_tty || exit 0
    # не обновляем: пусть Ghostty сам погасит красную через ~14 секунд
    state 2 100
    ;;
reset)
    open_tty || exit 0
    rm -f "$dir"/task.* 2>/dev/null
    rmdir "$holder" 2>/dev/null
    state 0
    ;;
*)
    echo "usage: progress.sh maybe-start|start|done|error|reset" >&2
    exit 2
    ;;
esac

exit 0
