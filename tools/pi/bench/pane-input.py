"""Real Pi/tmux parent input with 0/1/4 pi-subagents children using an offline 4 Hz provider."""
import argparse, os, sys, subprocess as sp, tempfile, time, threading, json, statistics, random, pty, termios, struct, fcntl
import queue
from pathlib import Path
