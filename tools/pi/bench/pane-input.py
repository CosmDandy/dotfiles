      wait(lambda f:live(),'live child streams',25)
      values=[];floors=[];rng=random.Random(123);initial_ticks=sum(l.startswith('tick ') for l in trace());
      for i in range(args.samples+1):
        prefix=f'LAT_{i:03}_'.encode();send(prefix);wait(lambda f:prefix in f,'prefix');time.sleep(rng.uniform(.055,.14))
        marker=chr(0x03b1+i).encode();t=time.perf_counter_ns();send(marker);seen=b''
        while time.perf_counter_ns()-t<2e9:
          ts,buf=output.get(timeout=2);
